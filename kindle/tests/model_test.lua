local model = dofile(arg[1] or 'plugins/kt2board.koplugin/model.lua')
local count = 0
local function test(name, f) f(); count=count+1; print('PASS '..name) end
local function sample()
 return {clock_valid=true,date='2026-10-17',tasks={{id=1,text='买牛奶',done=false},{id=2,text='阅读中文',done=true}},almanac={date='2026-10-17',available=true},weather={status='live',days={{date='2026-10-17',low=20,high=27,rain=25,condition='多云'}}}}
end
test('valid Chinese and completed tasks retained',function()
 local s=assert(model.validate(sample())); assert(#s.tasks==2 and s.tasks[2].done)
end)
test('malformed data rejected before replacing last screen',function()
 local s=sample();s.tasks[1].done='false';assert(model.validate(s)==nil)
 s=sample();s.tasks[2].id=1;assert(model.validate(s)==nil)
end)
test('missing forecast does not invent weather',function()
 local s=sample();s.weather={status='unavailable'};assert(model.validate(s));assert(model.day(s,0)==nil)
end)
test('wrong day almanac rejected',function()
 local s=sample();s.almanac.date='2026-10-16';assert(model.validate(s)==nil)
end)
test('request completion is explicit not toggle endpoint',function()
 local s=sample();local path,body=model.change(s,1);assert(path=='/api/tasks/1' and body.done==true)
 path,body=model.change(s,2);assert(body.done==false);assert(model.change(s,99)==nil)
end)
test('pagination includes completed items and clamps bounds',function()
 local s=sample();local rows,page,total=model.page(s,99,1);assert(page==2 and total==2 and rows[1].id==2)
 rows,page,total=model.page({tasks={}},1,4);assert(page==1 and total==1 and #rows==0)
end)
test('seventh day handles year and leap date without host timezone',function()
 assert(model.shiftDate('2026-12-31',1)=='2027-01-01')
 assert(model.shiftDate('2028-02-28',1)=='2028-02-29')
 assert(model.shiftDate('2026-10-17',6)=='2026-10-23')
end)
test('old forecast day not reused as today',function()
 local s=sample();s.weather.days={{date='2026-10-16',high=30}};assert(model.day(s,0)==nil)
end)
test('truncation never splits UTF8',function()
 assert(model.short('中文🙂abc',3)=='中文🙂…')
end)
test('render-unsafe forecast fields rejected',function()
 local s=sample();s.weather.days[1].low=nil;assert(model.validate(s)==nil)
 s=sample();s.weather.current={temperature='invalid',condition='晴'};assert(model.validate(s)==nil)
 s=sample();s.weather.days='bad';assert(model.validate(s)==nil)
end)
test('render-unsafe almanac fields rejected',function()
 local s=sample();s.almanac.yi='bad';assert(model.validate(s)==nil)
 s=sample();s.almanac.ji={false};assert(model.validate(s)==nil)
end)
test('JSON null weather accepted as missing without changing false booleans',function()
 require('setupkoenv');local JSON=require('json')
 local codec=dofile('plugins/kt2board.koplugin/codec.lua')
 local s=sample();s.weather={status='unavailable',current=JSON.util.null,days={}}
 local decoded=assert(codec.decode(JSON.encode(s)))
 assert(decoded.weather.current==nil and decoded.tasks[1].done==false)
 assert(model.validate(decoded));assert(codec.decode('{bad')==nil)
end)
print('MODEL_TESTS_OK '..count)
